import { useMemo, useState } from 'react';
import toast from 'react-hot-toast';
import { useReports, useGenerateReport, DailyReport } from '../hooks/useReports';
import { formatCurrency, formatReportDate, businessToday, businessDaysAgo } from '../lib/format';
import {
  ChartBarIcon,
  AlertTriangleIcon,
  PlusIcon,
  DownloadIcon,
  CheckCircleIcon,
} from '../components/ui/Icons';

export default function Reports() {
  const [start, setStart] = useState(() => businessDaysAgo(6));
  const [end, setEnd] = useState(() => businessToday());
  const [generateDate, setGenerateDate] = useState(() => businessToday());
  const [lastGenerated, setLastGenerated] = useState<DailyReport | null>(null);

  const { data: reports, isLoading, isError, error } = useReports(start, end);
  const generateReport = useGenerateReport();

  const totalInRange = useMemo(
    () => (reports || []).reduce((sum, r) => sum + Number(r.totalSalesAmount), 0),
    [reports]
  );

  const handleGenerate = async () => {
    if (!generateDate) {
      toast.error('Pick a date first');
      return;
    }
    if (generateDate > businessToday()) {
      toast.error('Cannot generate a report for a future date');
      return;
    }
    try {
      const report = await generateReport.mutateAsync(generateDate);
      setLastGenerated(report);
      toast.success(`Report generated for ${generateDate}`);
    } catch (err) {
      toast.error(err instanceof Error ? err.message : 'Failed to generate report');
    }
  };

  const handleExport = () => {
    if (!reports || reports.length === 0) {
      toast.error('Nothing to export');
      return;
    }
    const header = 'Date,Total (XAF),Generated by\n';
    const rows = reports
      .map(
        (r) =>
          `${r.reportDate.slice(0, 10)},${Number(r.totalSalesAmount)},"${r.generatedBy?.fullName ?? ''}"`
      )
      .join('\n');
    const blob = new Blob([header + rows], { type: 'text/csv;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `reports_${start}_${end}.csv`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4">
        <div>
          <h1 className="page-title">Reports</h1>
          <p className="text-gray-600 mt-1">Daily sales totals and report generation</p>
        </div>
        <button onClick={handleExport} className="btn-secondary" disabled={!reports || reports.length === 0}>
          <DownloadIcon className="w-4 h-4 mr-2" />
          Export CSV
        </button>
      </div>

      <div className="card">
        <div className="card-header">
          <h2 className="text-lg font-semibold text-gray-900">Generate daily report</h2>
        </div>
        <div className="card-body">
          <div className="flex flex-col sm:flex-row gap-3 sm:items-end">
            <div className="flex-1 max-w-xs">
              <label htmlFor="generate-date" className="label-field">Report date</label>
              <input
                id="generate-date"
                type="date"
                max={businessToday()}
                value={generateDate}
                onChange={(e) => setGenerateDate(e.target.value)}
                className="input-field"
              />
            </div>
            <button onClick={handleGenerate} className="btn-primary" disabled={generateReport.isPending}>
              <PlusIcon className="w-4 h-4 mr-2" />
              {generateReport.isPending ? 'Generating...' : 'Generate Report'}
            </button>
          </div>
          {lastGenerated && (
            <div className="mt-4 bg-green-50 border border-green-200 rounded-lg p-4 flex items-start gap-3 animate-fade-in">
              <CheckCircleIcon className="w-5 h-5 text-success mt-0.5" aria-hidden="true" />
              <div>
                <p className="text-sm font-medium text-green-900">
                  Report for {formatReportDate(lastGenerated.reportDate)} generated
                </p>
                <p className="text-sm text-green-800 mt-1">
                  Total sales: <span className="font-semibold">{formatCurrency(lastGenerated.totalSalesAmount)}</span>
                </p>
              </div>
            </div>
          )}
        </div>
      </div>

      <div className="card">
        <div className="card-header flex flex-col sm:flex-row sm:items-center sm:justify-between gap-3">
          <h2 className="text-lg font-semibold text-gray-900">Reports in range</h2>
          <div className="flex flex-col sm:flex-row gap-3 sm:items-end">
            <div>
              <label htmlFor="start-date" className="label-field">From</label>
              <input
                id="start-date"
                type="date"
                value={start}
                max={end}
                onChange={(e) => setStart(e.target.value)}
                className="input-field"
              />
            </div>
            <div>
              <label htmlFor="end-date" className="label-field">To</label>
              <input
                id="end-date"
                type="date"
                value={end}
                min={start}
                max={businessToday()}
                onChange={(e) => setEnd(e.target.value)}
                className="input-field"
              />
            </div>
          </div>
        </div>
        <div className="card-body">
          {isLoading ? (
            <div className="h-40 bg-gray-100 rounded animate-pulse" />
          ) : isError ? (
            <div className="text-center py-8">
              <AlertTriangleIcon className="w-10 h-10 text-danger mx-auto mb-3" />
              <p className="text-gray-600 mb-4">{error instanceof Error ? error.message : 'Failed to load reports'}</p>
            </div>
          ) : reports && reports.length > 0 ? (
            <>
              <div className="table-container">
                <table className="table-base">
                  <thead className="table-header">
                    <tr>
                      <th className="table-header-cell">Date</th>
                      <th className="table-header-cell text-right">Total sales</th>
                      <th className="table-header-cell">Generated by</th>
                    </tr>
                  </thead>
                  <tbody className="table-body divide-y divide-gray-100">
                    {reports.map((report) => (
                      <tr key={report.id} className="hover:bg-gray-50 transition-colors duration-100 ease-out">
                        <td className="table-cell font-medium">{formatReportDate(report.reportDate)}</td>
                        <td className="table-cell text-right font-medium">
                          {formatCurrency(report.totalSalesAmount)}
                        </td>
                        <td className="table-cell text-gray-600">
                          {report.generatedBy?.fullName || `User #${report.generatedById}`}
                        </td>
                      </tr>
                    ))}
                  </tbody>
                  <tfoot>
                    <tr className="bg-gray-50">
                      <td className="px-3 py-3 text-sm font-semibold text-gray-900">Range total</td>
                      <td className="px-3 py-3 text-sm font-bold text-gray-900 text-right">
                        {formatCurrency(totalInRange)}
                      </td>
                      <td />
                    </tr>
                  </tfoot>
                </table>
              </div>
              <p className="text-xs text-gray-500 mt-3">
                Dates without a generated report are skipped. Use the form above to generate one.
              </p>
            </>
          ) : (
            <div className="text-center py-8">
              <ChartBarIcon className="w-12 h-12 text-gray-300 mx-auto mb-3" />
              <p className="text-gray-500">No reports found in this date range.</p>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
